# Madlibs game
# This program will ask the user for a series of words
# then insert those words into a story template to create a funny story.

# Get user input
adjective1 = input("Enter an adjective(description): ")
noun1 = input("Enter a noun(person, place, or thing): ")
verb1 = input("Enter a verb(action ending with 'ing'): ")
adjective2 = input("Enter another adjective: ")
adjective3 = input("Enter one more adjective: ")

# Create the story template
print(f"Today I went to a {adjective1} park")
print(f'and I saw {noun1} placed in the middle of the park.')
print(f'It was {verb1} around and having fun')
print(f'It was a {adjective2} day and the weather was {adjective3}!')

