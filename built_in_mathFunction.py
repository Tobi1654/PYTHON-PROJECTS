
x = 5
y = 7.3
z = 2 

# Using the built-in round() function to round y to the nearest integer
result = round(y)

# Using the built-in abs() function to get the absolute value of z
result = abs(z)

# Using the built-in pow() function to calculate x raised to the power of z
result = pow(5,2)

# Using the built-in max() function to find the maximum of x, y, and z
result = max(x, y, z)

# Using the built-in min() function to find the minimum of x, y, and z
result = min(x, y, z)

print(result)



# Inbuilt math funtiond from math module
import math

