#1. Area of a Rec tangle
# The area of a rectangle is calculated by multiplying its length by its width.
# formula is A = l * w

# wrap the input() function with float() to convert the user input from a string to a float number
length = float(input("Enter your length: ")) # wrap the input() function with float() to convert the user input from a string to a floating-point number
width = float(input("Enter your width: "))

area = length * width

print(area)